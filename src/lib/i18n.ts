export function formatStudyDate(dayKey: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === 'zh' ? 'zh-CN' : 'en-US', { weekday: 'short' }).format(new Date(`${dayKey}T12:00:00`));
}
