const getEnglishGloss = (languageId: LanguageId, verb: VerbEntry) =>
  languageId === 'english' ? '' : (englishGlosses[languageId][verb.infinitive] ?? '');

/** English verbs have no English gloss: the infinitive already is one. */
export const getVerbTranslation = (
  language: Pick<Language, 'id'>,
  verb: VerbEntry,
  translationLanguage: TranslationLanguage,
) => (translationLanguage === 'zh' ? verb.translation : getEnglishGloss(language.id, verb));

/** Every gloss the Word Book search should match, regardless of the chosen display language. */
export const getVerbSearchText = (language: Pick<Language, 'id'>, verb: VerbEntry) =>
  `${verb.infinitive} ${verb.translation} ${getEnglishGloss(language.id, verb)}`.toLowerCase();
